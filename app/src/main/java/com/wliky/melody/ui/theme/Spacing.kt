package com.wliky.melody.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 间距 token。页面布局一律从这里取值，不硬编码 dp。
 */
object Spacing {
    val xs: Dp = 4.dp
    val sm: Dp = 8.dp
    val md: Dp = 16.dp
    val lg: Dp = 24.dp
    val xl: Dp = 32.dp

    /** 页面水平内边距 */
    val screen: Dp = 20.dp
}
